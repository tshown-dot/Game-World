const { chromium } = require('playwright');
const BASE=process.env.BASE||'http://localhost:3112/';
const OUT=(process.env.OUT||require('path').join(__dirname,'screenshots'))+'/counterweight_story'; require('fs').mkdirSync(OUT,{recursive:true});
const ROOT_RE=new RegExp('^'+BASE.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')+'(index\\.html)?(\\?.*)?$');
const URL=BASE+'towns/topic-4-equation-valley/games/4-2-counterweight/index.html?test';
let checks=0, fails=0; const ok=(c,m)=>{ checks++; if(!c){fails++; console.log('  FAIL:',m);} else console.log('  ok:',m); };
const G=(p,f)=>p.evaluate(f);
(async()=>{
  const b=await chromium.launch(); const ctx=await b.newContext({viewport:{width:1366,height:768}});
  await ctx.route('https://fonts.googleapis.com/**',r=>r.fulfill({contentType:'text/css',body:''}));
  const errs=[]; const p=await ctx.newPage(); p.on('pageerror',e=>errs.push(e.message));
  await p.goto(URL,{waitUntil:'load'}); await p.keyboard.press('Enter');
  await p.waitForFunction(()=>{ const g=window.__counterweight.G; return g.problem && g.intro; },null,{timeout:8000});
  const start=await G(p,()=>{ const pr=window.__counterweight.G.problem; return { start: pr.start.left.text+' = '+pr.start.right.text, sab: pr.sabotage }; });
  console.log('\n[1] Beat 1: the scale starts balanced ('+start.start+')');
  await p.waitForTimeout(400);
  ok(/BALANCED ✓/.test(await p.textContent('#scene')),'the scale shows BALANCED ✓');
  ok((await p.textContent('#eqStrip .eq-line')).replace(/\s+/g,' ').trim()===start.start.replace(/\s+/g,' '),'the strip shows the starting equation: '+start.start);
  ok(/=/.test(await p.textContent('#eqStrip .eq-value')) && !/≠/.test(await p.textContent('#eqStrip .eq-value')),'and both sides are equal');
  ok(/Heh heh/.test(await p.textContent('#scene')),'the Saboteur is there, plotting');
  await p.screenshot({path:OUT+'/1_balanced.png'});
  console.log('\n[2] Beat 2: the Saboteur strikes ('+start.sab.op+' '+start.sab.n+' on the '+start.sab.side+')');
  await p.waitForTimeout(1300);
  const sabSpan=await p.$eval('#eqStrip .sab',e=>e.textContent).catch(()=>null);
  ok(sabSpan && sabSpan.includes(String(start.sab.n)),'his change appears in red in the equation: "'+sabSpan+'"');
  ok(/≠/.test(await p.textContent('#eqStrip .eq-value')),'the value line now says the sides are NOT equal');
  ok(/NOT BALANCED/.test(await p.textContent('#scene')),'the scale sign says NOT BALANCED');
  ok(new RegExp(String(start.sab.n)+'!').test(await p.textContent('#scene')),'his speech bubble says what he did');
  await p.screenshot({path:OUT+'/2_sabotage.png'});
  console.log('\n[3] Beat 3: tipped, and the student can act');
  await p.waitForFunction(()=>!window.__counterweight.G.intro,null,{timeout:5000});
  ok(!(await G(p,()=>window.__counterweight.G.locked)),'controls unlock after the story');
  const theta=await G(p,()=>window.__counterweight.G.theta); ok(Math.abs(theta)>1,'the beam is tipped ('+theta.toFixed(1)+'°)');
  ok(/Before:.*balanced/.test(await p.textContent('#prompt')),'the side panel tells the story in words too');
  console.log('\n[4] The student fixes it');
  await p.click(`[data-op="${start.sab.op}"]`); for(const d of String(start.sab.n)) await p.click(`[data-digit="${d}"]`);
  ok((await p.textContent('#block')).replace(/\s+/g,' ').includes(String(start.sab.n)),'the student built a block: '+(await p.textContent('#block')));
  const fix=start.sab.side==='left'?'#panR':'#panL';
  const bb=await (await p.$('#block')).boundingBox(); const pan=await (await p.$(fix)).boundingBox();
  await p.mouse.move(bb.x+bb.width/2, bb.y+bb.height/2); await p.mouse.down();
  await p.mouse.move((bb.x+pan.x+pan.width/2)/2, (bb.y+pan.y+pan.height/2)/2, {steps:6});
  await p.mouse.move(pan.x+pan.width/2, pan.y+pan.height/2, {steps:6});
  ok(await p.isVisible('.block.ghost'),'while dragging, the block follows the pointer');
  ok(await p.$eval(fix,e=>e.classList.contains('drop-target')),'and the pan under it glows');
  await p.screenshot({path:OUT+'/3a_dragging.png'});
  await p.mouse.up();
  ok(!(await p.$('.block.ghost')),'letting go drops the block');
  await p.waitForTimeout(500);
  const you=await p.$eval('#eqStrip .you',e=>e.textContent).catch(()=>null);
  ok(you && you.includes(String(start.sab.n)),'the student\'s move appears in blue: "'+you+'"');
  ok(/✓/.test(await p.textContent('#eqStrip .eq-value')),'the value line shows both sides equal again ✓');
  ok(/BALANCED ✓/.test(await p.textContent('#scene')),'the scale says BALANCED ✓ again');
  await p.screenshot({path:OUT+'/3_fixed.png'});
  console.log('\n[5] Skipping the story');
  await p.waitForFunction(()=>{ const g=window.__counterweight.G; return g.intro; },null,{timeout:8000});
  const t0=Date.now(); await p.keyboard.press('Enter');
  await p.waitForFunction(()=>!window.__counterweight.G.intro,null,{timeout:2000});
  ok(Date.now()-t0<600,'Enter skips straight to play ('+(Date.now()-t0)+' ms)');
  console.log('\n[6] Block Puzzles: the move happens to both sides');
  await p.goto(URL,{waitUntil:'load'}); await p.click('[data-zone="2"]'); await p.keyboard.press('Enter');
  await p.waitForFunction(()=>{ const g=window.__counterweight.G; return g.problem && !g.locked && !g.intro && document.getElementById('banner').classList.contains('hidden'); },null,{timeout:10000});
  const iso=await G(p,()=>{ const pr=window.__counterweight.G.problem; return { type: pr.type, ans: pr.answer }; });
  if(iso.type==='isolate'){
    await p.click(`[data-op="${iso.ans.op}"]`); for(const d of String(iso.ans.n)) await p.click(`[data-digit="${d}"]`);
    await p.keyboard.press('ArrowLeft'); await p.waitForTimeout(500);
    ok((await p.$$eval('#eqStrip .you',e=>e.length))===1,'after the first block, only the left side has changed');
    ok(/NOT BALANCED/.test(await p.textContent('#scene')),'so the scale tips');
    ok(/RIGHT pan needs the same block/.test(await p.textContent('#trayHelp')),'and the tray says the RIGHT pan needs the same block');
    await p.screenshot({path:OUT+'/4a_one_side.png'});
    await p.keyboard.press('ArrowLeft'); await p.waitForTimeout(200);
    ok(/already has its block/.test(await p.textContent('#trayHelp')) && (await G(p,()=>window.__counterweight.G.attempts))===0,'dropping on the same pan again gets a reminder, not a miss');
    await p.click('#block'); const pr=await (await p.$('#panR')).boundingBox(); await p.mouse.click(pr.x+pr.width/2, pr.y+pr.height/2); await p.waitForTimeout(500);
    ok((await p.$$eval('#eqStrip .you',e=>e.length))===2,'tap the block, tap the right pan: the strip shows the same blue step on BOTH sides');
    ok(/BALANCED ✓/.test(await p.textContent('#scene')),'and the scale levels');
    await p.screenshot({path:OUT+'/4_both_sides.png'});
  } else ok(true,'(first zone-3 problem was not an isolate; skipped)');
  console.log('\n[7] A different block on each pan is caught');
  await p.goto(URL,{waitUntil:'load'}); await p.click('[data-zone="2"]'); await p.keyboard.press('Enter');
  await p.waitForFunction(()=>{ const g=window.__counterweight.G; return g.problem && !g.locked && !g.intro && document.getElementById('banner').classList.contains('hidden'); },null,{timeout:10000});
  const iso2=await G(p,()=>{ const pr=window.__counterweight.G.problem; return { type: pr.type, ans: pr.answer }; });
  if(iso2.type==='isolate'){
    await p.click(`[data-op="${iso2.ans.op}"]`); for(const d of String(iso2.ans.n)) await p.click(`[data-digit="${d}"]`); await p.keyboard.press('ArrowRight');
    for(const _ of String(iso2.ans.n)) await p.keyboard.press('Backspace'); for(const d of String(iso2.ans.n+1)) await p.click(`[data-digit="${d}"]`); await p.keyboard.press('ArrowLeft');
    await p.waitForTimeout(300);
    ok(/SAME block/.test(await p.textContent('#feedback')),'the hint says both pans need the SAME block');
    await p.screenshot({path:OUT+'/5_mismatch.png'});
  } else ok(true,'(skipped)');
  ok(errs.length===0,'no page errors'+(errs.length?': '+errs.join(' | '):''));
  await b.close(); console.log(`\n${checks-fails}/${checks} checks passed`); process.exit(fails?1:0);
})().catch(e=>{console.error('SCRIPT ERROR',e.message.split('\n')[0]);process.exit(2);});
